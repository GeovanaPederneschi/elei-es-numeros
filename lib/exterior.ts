const INDICE = new Map<string, CidadeExterior>();
for (const [nomes, pais, iso, lat, lon] of T) for (const n of nomes) INDICE.set(normalizar(n), { pais, iso, lat, lon });

export function localizarCidade(nome: string): CidadeExterior | undefined {
  const n = normalizar(nome);
  if (INDICE.has(n)) return INDICE.get(n);
  // tenta sem sufixos como "- EUA" ou "(PORTUGAL)"
  const base = normalizar(nome.split(/[-(,/]/)[0]);
  return INDICE.get(base);
}
